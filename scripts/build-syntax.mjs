import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {build, transform} from 'esbuild';
import {highlightText, resolveLanguage} from './syntax-source.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = path.join(root, 'node_modules/highlight.js');
const version = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8')).version;
const banner = `/*! highlight.js ${version} | BSD-3-Clause | Copyright (c) 2006 Ivan Sagalaev | https://highlightjs.org/\n * GitHub / GitHub Dark themes by github.com, maintained by @Hirse.\n * Generated by npm run build:syntax; full license: ./syntax.LICENSE.txt. */`;

function scopeTheme(filename, scope) {
  const css = fs.readFileSync(path.join(packageRoot, 'styles', filename), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  if (css.includes('@')) throw new Error('Review new upstream theme at-rules before scoping');
  return css.replace(/([^{}]+)\{([^{}]*)\}/g, (_rule, selectors, declarations) =>
    selectors.split(',').map(selector => `${scope} .article-content ${selector.trim()}`).join(',') + `{${declarations}}`);
}

const css = [
  scopeTheme('github.css', ':root:not([data-theme="dark"])'),
  scopeTheme('github-dark.css', ':root[data-theme="dark"]'),
  ':root:not([data-theme="dark"]) .article-content pre.syntax-highlighted{background:#ffffff;color:#24292e}',
  ':root[data-theme="dark"] .article-content pre.syntax-highlighted{background:#0d1117;color:#c9d1d9}',
  ':root .article-content pre.syntax-highlighted>code.hljs{display:block;padding:0;overflow:visible;background:transparent;color:inherit}',
].join('\n');

fs.mkdirSync(path.join(root, 'public'), {recursive: true});
fs.mkdirSync(path.join(root, 'LICENSES'), {recursive: true});
fs.copyFileSync(path.join(packageRoot, 'LICENSE'), path.join(root, 'public/syntax.LICENSE.txt'));
fs.copyFileSync(path.join(packageRoot, 'LICENSE'), path.join(root, 'LICENSES/HIGHLIGHT-JS-LICENSE.txt'));
fs.copyFileSync(path.join(root, 'node_modules/esbuild/LICENSE.md'), path.join(root, 'LICENSES/ESBUILD-LICENSE.txt'));
await build({
  entryPoints: [path.join(root, 'scripts/syntax-source.mjs')],
  outfile: path.join(root, 'public/syntax.js'), bundle: true, platform: 'browser', format: 'iife',
  target: ['es2020'], minify: true, legalComments: 'inline', banner: {js: banner}, charset: 'utf8',
});
const minified = await transform(css, {loader: 'css', minify: true, target: 'es2020'});
fs.writeFileSync(path.join(root, 'public/syntax.css'), banner + '\n' + minified.code);

if (process.argv.includes('--check')) {
  const samples = [
    ['c++', '#include <vulkan/vulkan.hpp>\nconst char* value = "<script>alert(1)</script> & \\"quoted\\"";\nreturn 0;'],
    ['glsl', '#version 450\nlayout(location = 0) out vec4 outColor;\nvoid main() { outColor = vec4(1.0); }'],
    ['slang', '[shader("vertex")]\nfloat4 main(uint vertexID : SV_VertexID) : SV_Position { return float4(1.0); }'],
    ['cmake', 'find_package(Vulkan REQUIRED)\ntarget_link_libraries(app PRIVATE Vulkan::Vulkan)'],
    ['shell', 'cmake -S . -B build\nprintf \'<img src=x onerror=alert(1)>\\n\''],
    ['xml', '<configuration value="a &amp; b"><item>text</item></configuration>'],
  ];
  const decode = value => value.replace(/<\/?span\b[^>]*>/g, '').replace(/&(amp|lt|gt|quot|#x27|#39);/g, (_entity, name) => ({amp: '&', lt: '<', gt: '>', quot: '"', '#x27': "'", '#39': "'"})[name]);
  for (const [label, source] of samples) {
    const highlighted = highlightText(source, label);
    assert.ok(highlighted?.html.includes('hljs-'), `${label} produces syntax tokens`);
    assert.equal(decode(highlighted.html), source, `${label} preserves exact code text`);
    assert.ok(!/<(?:script|img)\b/i.test(highlighted.html), `${label} escapes source markup`);
  }
  for (const label of ['', undefined, 'text', 'plaintext', 'nohighlight', 'output', 'unknown-language']) {
    assert.equal(highlightText('int value = 1;', label), null, `${label} is not guessed`);
  }
  assert.equal(resolveLanguage('C++'), 'cpp');
  assert.equal(resolveLanguage('shell'), 'bash');
  console.log('Syntax checks passed: explicit languages, escaped markup and exact text preservation.');
}

for (const name of ['syntax.js', 'syntax.css']) console.log(`${name}: ${fs.statSync(path.join(root, 'public', name)).size} bytes`);
